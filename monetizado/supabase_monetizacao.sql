-- ---------------------------------------------------------------------------
-- 1) Perfis (1 perfil por usuário do Supabase Auth)
--    Guarda chave Groq do próprio professor, modelo e saldo de créditos.
-- ---------------------------------------------------------------------------
create table if not exists public.perfis (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade unique,
  nome text not null default '',
  unidade text not null default '',
  groq_api_key text not null default '',
  groq_model text not null default 'openai/gpt-oss-120b',
  credito_inicial integer not null default 15,
  is_admin boolean not null default false,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 2) Catálogo de pacotes de créditos vendáveis
-- ---------------------------------------------------------------------------
create table if not exists public.planos (
  id bigint generated by default as identity primary key,
  nome text not null,
  creditos integer not null,
  preco_centavos integer not null,
  destaque boolean not null default false,
  ativo boolean not null default true,
  ordem integer not null default 0
);

